export function fillSiyumNusachMasechet(text: string, masechetHe: string): string {
  return text.split(SIYUM_MASECHET_PLACEHOLDER).join(masechetHe);
}

export function getSiyumNusachSections(masechetHe: string): SiyumNusachSection[] {
  return SIYUM_NUSACH_SECTIONS.map((section) => ({
    ...section,
    body: fillSiyumNusachMasechet(section.body, masechetHe),
  }));
}
